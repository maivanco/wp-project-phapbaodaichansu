<script>
document.addEventListener('DOMContentLoaded', function() {
  const cards = Array.from(document.querySelectorAll('#testimonials-grid .testimonial-card'));
  const itemsPerPage = 3;
  let currentPage = 1;
  const totalPages = Math.ceil(cards.length / itemsPerPage);

  const prevBtn = document.getElementById('prev-page-btn');
  const nextBtn = document.getElementById('next-page-btn');
  const pageNumbersContainer = document.getElementById('page-numbers-container');

  function renderPagination() {
    // Show/hide cards for currentPage
    cards.forEach((card, index) => {
      const pageIndex = Math.floor(index / itemsPerPage) + 1;
      if (pageIndex === currentPage) {
        card.style.display = 'flex';
        setTimeout(() => { card.style.opacity = '1'; }, 50);
      } else {
        card.style.opacity = '0';
        card.style.display = 'none';
      }
    });

    // Update prev/next button states
    if (prevBtn) prevBtn.disabled = (currentPage === 1);
    if (nextBtn) nextBtn.disabled = (currentPage === totalPages || totalPages === 0);

    // Render numeric buttons
    if (pageNumbersContainer) {
      pageNumbersContainer.innerHTML = '';
      for (let i = 1; i <= totalPages; i++) {
        const btn = document.createElement('button');
        btn.type = 'button';
        btn.className = `w-9 h-9 rounded-lg text-xs font-semibold font-sans transition-all duration-200 ${
          i === currentPage 
            ? 'bg-[#1a747a] text-white shadow-sm' 
            : 'bg-white border border-[#2d2a26]/15 text-gray-700 hover:bg-[#1a747a]/10 hover:text-[#1a747a]'
        }`;
        btn.textContent = i;
        btn.addEventListener('click', () => {
          currentPage = i;
          renderPagination();
        });
        pageNumbersContainer.appendChild(btn);
      }
    }
  }

  if (prevBtn) {
    prevBtn.addEventListener('click', () => {
      if (currentPage > 1) {
        currentPage--;
        renderPagination();
      }
    });
  }

  if (nextBtn) {
    nextBtn.addEventListener('click', () => {
      if (currentPage < totalPages) {
        currentPage++;
        renderPagination();
      }
    });
  }

  // Initial pagination render
  renderPagination();

  // Modal logic
  const modal = document.getElementById('testimonial-modal');
  const modalContent = document.getElementById('testimonial-modal-content');
  const closeModalBtn = document.getElementById('close-testimonial-modal');
  const modalBtns = document.querySelectorAll('.open-testimonial-modal');

  modalBtns.forEach(btn => {
    btn.addEventListener('click', function(e) {
      e.stopPropagation();
      document.getElementById('modal-name').textContent = this.getAttribute('data-name');
      document.getElementById('modal-sub').textContent = this.getAttribute('data-sub');
      document.getElementById('modal-title').textContent = '"' + this.getAttribute('data-title') + '"';
      document.getElementById('modal-fulltext').textContent = '"' + this.getAttribute('data-fulltext') + '"';
      document.getElementById('modal-date').textContent = this.getAttribute('data-date');
      
      const name = this.getAttribute('data-name') || '';
      const initials = name.split(' ').map(n => n[0]).join('').slice(-2);
      document.getElementById('modal-avatar').textContent = initials;

      modal.classList.remove('opacity-0', 'pointer-events-none');
      modal.classList.add('opacity-100');
      modalContent.classList.remove('scale-95');
      modalContent.classList.add('scale-100');
    });
  });

  function closeModal() {
    if (!modal) return;
    modal.classList.remove('opacity-100');
    modal.classList.add('opacity-0', 'pointer-events-none');
    modalContent.classList.remove('scale-100');
    modalContent.classList.add('scale-95');
  }

  if (closeModalBtn) {
    closeModalBtn.addEventListener('click', closeModal);
  }

  if (modal) {
    modal.addEventListener('click', function(e) {
      if (e.target === modal) closeModal();
    });
  }
});
</script>
